#!/usr/bin/env python3
"""Compose core/ + a profile into every harness. Run after editing anything under core/.

    scripts/sync.py                         regenerate harness/ with the default profile
    scripts/sync.py --profile areasim       pick a profile from profiles/
    scripts/sync.py --check                 exit 1 if a harness is stale, changing nothing
    scripts/sync.py --install DIR           also install into DIR/.claude (and DIR/.cursor),
                                            and copy the login helper into DIR/webtesterEnv/

core/ is project-neutral and is the single source of truth for method. profiles/<name>.md
holds the facts about one project, and is injected where a skill says `<!-- profile -->`.
Everything under harness/ is generated: never hand-edit it, the next sync overwrites it.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE, PROFILES, HARNESS = ROOT / "core", ROOT / "profiles", ROOT / "harness"
# Third-party skills, pinned and reviewed. Installed as-is: no profile splice, no banner.
# Each carries a SOURCE.md (commit, local changes) that stays here, not in the install.
VENDOR = ROOT / "vendor"
BANNER = "<!-- generated by scripts/sync.py from core/. Do not edit by hand. -->"
MARKER = "<!-- profile -->"
# The web tester's per-machine folder in the installed project: the login helper is copied
# here, and the Playwright venv is created here (webtesterEnv/.venv), so a teammate needs
# only the workspace, not this checkout. Profiles name the paths under it.
WEBTESTER_DIR = "webtesterEnv"
WEBTESTER_FILES = ("login.py",)

# Hooks from core/hooks/: script -> (event, tool matcher or None). A plugin install reads
# hooks/hooks.json from the plugin root; a copy install has no such file, so the entries
# are merged into settings.json.
HOOKS = {
    "fe-flow-status.py": ("SessionStart", None),
    "fe-guard-secrets.py": ("PreToolUse", "Read|Edit|Write|MultiEdit|NotebookEdit|Bash|Grep|Glob"),
}
PLUGIN_HOOK_CMD = 'python3 "${CLAUDE_PLUGIN_ROOT}/hooks/%s"'
INSTALL_HOOK_CMD = 'python3 "$CLAUDE_PROJECT_DIR/.claude/hooks/%s"'

# command file stem -> (namespace, command name). /fe:spec comes from commands/fe-spec.md
COMMANDS = {
    "fe-spec": ("fe", "spec"),
    "fe-plan": ("fe", "plan"),
    "fe-test": ("fe", "test"),
    "fe-build": ("fe", "build"),
    "fe-audit": ("fe", "audit"),
    "fe-e2e": ("fe", "e2e"),
    "fe-run": ("fe", "run"),
    "git-commit": ("git", "commit"),
    "git-pr": ("git", "pr"),
}


def read_profile(name):
    path = PROFILES / f"{name}.md"
    if not path.exists():
        available = ", ".join(sorted(p.stem for p in PROFILES.glob("*.md"))) or "none"
        sys.exit(f"no profile {name!r} in profiles/ (have: {available})")
    return path.read_text().strip()


def compose_skill(skill_dir, profile_text, profile_name):
    """SKILL.md with the profile spliced in; references copied unchanged."""
    out = {}
    text = (skill_dir / "SKILL.md").read_text()
    if MARKER not in text:
        sys.exit(f"{skill_dir.name}/SKILL.md has no {MARKER} marker")
    header, _, _ = text.partition(MARKER)
    body = f"{header.rstrip()}\n\n---\n\n{BANNER}\n\n{profile_text}\n"
    # Banner goes under the frontmatter too, so an installed copy declares its origin.
    front_end = body.index("---\n", 4) + 4
    body = body[:front_end] + f"\n{BANNER}\n<!-- profile: {profile_name} -->\n" + body[front_end:]
    out["SKILL.md"] = body
    for ref in sorted((skill_dir / "references").glob("*.md")):
        out[f"references/{ref.name}"] = ref.read_text()
    return out


def vendor_skills():
    """skill name -> {relative path: text} for each vendored skill."""
    skills = {}
    for skill_dir in sorted(VENDOR.iterdir()) if VENDOR.is_dir() else []:
        if not (skill_dir / "SKILL.md").exists():
            continue
        skills[skill_dir.name] = {
            str(f.relative_to(skill_dir)): f.read_text()
            for f in sorted(skill_dir.rglob("*"))
            if f.is_file() and f.name not in {"SOURCE.md", ".DS_Store"}
        }
    return skills


def build_claude(profile_text, profile_name):
    """path (relative to a .claude dir) -> file contents."""
    files = {}
    for name, skill_files in vendor_skills().items():
        for rel, text in skill_files.items():
            files[f"skills/{name}/{rel}"] = text
    for skill_dir in sorted((CORE / "skills").iterdir()):
        if not skill_dir.is_dir():
            continue
        for rel, text in compose_skill(skill_dir, profile_text, profile_name).items():
            files[f"skills/{skill_dir.name}/{rel}"] = text
    for agent in sorted((CORE / "agents").glob("*.md")):
        files[f"agents/{agent.name}"] = agent.read_text()
    for cmd in sorted((CORE / "commands").glob("*.md")):
        if cmd.stem not in COMMANDS:
            sys.exit(f"commands/{cmd.name} is not in COMMANDS in sync.py")
        namespace, name = COMMANDS[cmd.stem]
        files[f"commands/{namespace}/{name}.md"] = cmd.read_text()
    for hook in hook_scripts():
        files[f"hooks/{hook.name}"] = hook.read_text()
    return files


def hook_scripts():
    scripts = sorted((CORE / "hooks").glob("*.py"))
    for script in scripts:
        if script.name not in HOOKS:
            sys.exit(f"hooks/{script.name} is not in HOOKS in sync.py")
    return scripts


def hook_entry(command, matcher):
    entry = {"hooks": [{"type": "command", "command": command, "timeout": 10}]}
    return {"matcher": matcher, **entry} if matcher else entry


def plugin_hooks_json():
    """hooks/hooks.json for the plugin route, where ${CLAUDE_PLUGIN_ROOT} resolves."""
    events = {}
    for h in hook_scripts():
        event, matcher = HOOKS[h.name]
        events.setdefault(event, []).append(hook_entry(PLUGIN_HOOK_CMD % h.name, matcher))
    return json.dumps({"hooks": events}, indent=2) + "\n"


def merge_settings_hooks(claude_dir):
    """Add each hook to DIR/.claude/settings.json once, leaving everything else as it was."""
    path = claude_dir / "settings.json"
    settings = json.loads(path.read_text()) if path.exists() else {}
    added = []
    for hook in hook_scripts():
        event_name, matcher = HOOKS[hook.name]
        event = settings.setdefault("hooks", {}).setdefault(event_name, [])
        existing = {h.get("command") for e in event for h in e.get("hooks", [])}
        command = INSTALL_HOOK_CMD % hook.name
        # Match on the script name too, so a hand-tweaked command is not added twice.
        if command in existing or any(hook.name in (c or "") for c in existing):
            continue
        event.append(hook_entry(command, matcher))
        added.append(f"{event_name} {hook.name}")
    if added:
        path.write_text(json.dumps(settings, indent=2) + "\n")
    return added


# Cursor reads skills as rules (.cursor/rules/<skill>.mdc, references inlined), so the agents
# and commands, written for Claude Code, get this note in front of their body.
CURSOR_NOTE = (
    "> **In Cursor:** a skill named here is the rule `.cursor/rules/<skill>.mdc`, and each of "
    "its `references/<name>.md` files is inlined in that rule under a "
    "`<!-- references/<name>.md -->` marker. An agent named here is the subagent "
    "`.cursor/agents/<name>.md`, and a command written `/fe:build` or `/git:pr` is "
    "`/fe-build` or `/git-pr` here.\n"
)


def split_frontmatter(text):
    """(frontmatter lines without the --- fences, body) for a file that starts with ---."""
    if not text.startswith("---\n"):
        return [], text
    end = text.index("\n---\n", 4)
    return text[4:end].splitlines(), text[end + 5:]


def cursor_agent(text):
    """A core agent as a Cursor subagent: Claude model aliases become `inherit`."""
    front, body = split_frontmatter(text)
    front = ["model: inherit" if line.startswith("model:") else line for line in front]
    return "---\n" + "\n".join(front) + f"\n---\n\n{BANNER}\n\n{CURSOR_NOTE}\n{body.lstrip()}"


def cursor_command(text, invocation):
    """A core command as a Cursor command: plain prompt, no frontmatter, no $ARGUMENTS."""
    front, body = split_frontmatter(text)
    description = next((l.split(":", 1)[1].strip() for l in front if l.startswith("description:")), "")
    body = body.replace("$ARGUMENTS", "the text given after the command (if any)")
    return (f"{BANNER}\n\n# {invocation}\n\n{description}\n\n{CURSOR_NOTE}\n{body.lstrip()}")


def build_cursor(profile_text, profile_name):
    """One .mdc rule per skill, plus the agents as subagents and the commands as /<ns>-<name>."""
    files = {}
    for skill_dir in sorted((CORE / "skills").iterdir()):
        if not skill_dir.is_dir():
            continue
        composed = compose_skill(skill_dir, profile_text, profile_name)
        parts = [composed["SKILL.md"]]
        for rel, text in composed.items():
            if rel != "SKILL.md":
                parts.append(f"\n\n---\n\n<!-- {rel} -->\n\n{text}")
        files[f"rules/{skill_dir.name}.mdc"] = "".join(parts)
    for name, skill_files in vendor_skills().items():
        files[f"rules/{name}.mdc"] = skill_files["SKILL.md"]
    for agent in sorted((CORE / "agents").glob("*.md")):
        files[f"agents/{agent.name}"] = cursor_agent(agent.read_text())
    for cmd in sorted((CORE / "commands").glob("*.md")):
        if cmd.stem not in COMMANDS:
            sys.exit(f"commands/{cmd.name} is not in COMMANDS in sync.py")
        namespace, name = COMMANDS[cmd.stem]
        # Cursor commands are flat files: /fe:run in Claude Code is /fe-run here.
        files[f"commands/{namespace}-{name}.md"] = cursor_command(
            cmd.read_text(), f"/{namespace}-{name}")
    return files


def webtester_files():
    """The browser-run helpers copied into the project, each marked as a generated copy."""
    files = {}
    for name in WEBTESTER_FILES:
        text = (ROOT / "scripts" / name).read_text()
        shebang, _, rest = text.partition("\n")
        files[name] = (f"{shebang}\n# generated copy of frontend-plugin/scripts/{name} by "
                       f"scripts/sync.py --install. Do not edit here.\n{rest}")
    return files


def write_tree(base, files, check):
    """Write files under base. Returns the paths that differ (check) or were written."""
    changed = []
    for rel, text in sorted(files.items()):
        path = base / rel
        if check:
            if not path.exists() or path.read_text() != text:
                changed.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            changed.append(path)
    return changed


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--profile", default="areasim", help="a name from profiles/")
    ap.add_argument("--check", action="store_true", help="report staleness, write nothing")
    ap.add_argument("--install", metavar="DIR", help="also install into DIR/.claude")
    args = ap.parse_args()

    profile_text = read_profile(args.profile)
    claude = build_claude(profile_text, args.profile)
    cursor = build_cursor(profile_text, args.profile)

    changed = []
    changed += write_tree(HARNESS / "claude", {**claude, "hooks/hooks.json": plugin_hooks_json()},
                          args.check)
    changed += write_tree(HARNESS / "cursor", cursor, args.check)

    if args.check:
        if changed:
            print("stale:")
            for path in changed:
                print(" ", path.relative_to(ROOT))
            sys.exit(1)
        print("harness is up to date")
        return

    if args.install:
        target = Path(args.install).expanduser().resolve()
        if not target.is_dir():
            sys.exit(f"{target} is not a directory")
        installed = write_tree(target / ".claude", claude, False)
        installed += write_tree(target / ".cursor", cursor, False)
        helpers = webtester_files()
        installed += write_tree(target / WEBTESTER_DIR, helpers, False)
        print(f"installed {len(claude) + len(cursor)} files into {target}, "
              f"{len(helpers)} into {WEBTESTER_DIR}/")
        for name in merge_settings_hooks(target / ".claude"):
            print(f"added hook {name} to .claude/settings.json")

    print(f"synced {len(claude) + len(cursor)} files (profile: {args.profile}), "
          f"{len(changed)} changed")


if __name__ == "__main__":
    main()
