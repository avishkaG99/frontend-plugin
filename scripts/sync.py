#!/usr/bin/env python3
"""Compose core/ + a profile into every harness. Run after editing anything under core/.

    scripts/sync.py                         regenerate harness/ with the default profile
    scripts/sync.py --profile areasim       pick a profile from profiles/
    scripts/sync.py --check                 exit 1 if a harness is stale, changing nothing
    scripts/sync.py --install DIR           also install into DIR/.claude (and DIR/.cursor)

core/ is project-neutral and is the single source of truth for method. profiles/<name>.md
holds the facts about one project, and is injected where a skill says `<!-- profile -->`.
Everything under harness/ is generated: never hand-edit it, the next sync overwrites it.
"""
import argparse
import filecmp
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE, PROFILES, HARNESS = ROOT / "core", ROOT / "profiles", ROOT / "harness"
BANNER = "<!-- generated by scripts/sync.py from core/. Do not edit by hand. -->"
MARKER = "<!-- profile -->"

# command file stem -> (namespace, command name). /fe:spec comes from commands/fe-spec.md
COMMANDS = {
    "fe-spec": ("fe", "spec"),
    "fe-plan": ("fe", "plan"),
    "fe-test": ("fe", "test"),
    "fe-build": ("fe", "build"),
    "fe-audit": ("fe", "audit"),
    "fe-e2e": ("fe", "e2e"),
    "git-commit": ("git", "commit"),
    "git-pr": ("git", "pr"),
}


def read_profile(name):
    path = PROFILES / f"{name}.md"
    if not path.exists():
        available = ", ".join(sorted(p.stem for p in PROFILES.glob("*.md"))) or "none"
        sys.exit(f"no profile {name!r} in profiles/ (have: {available})")
    return path.read_text().strip()


def compose_skill(skill_dir, profile_text, profile_name):
    """SKILL.md with the profile spliced in; references copied unchanged."""
    out = {}
    text = (skill_dir / "SKILL.md").read_text()
    if MARKER not in text:
        sys.exit(f"{skill_dir.name}/SKILL.md has no {MARKER} marker")
    header, _, _ = text.partition(MARKER)
    body = f"{header.rstrip()}\n\n---\n\n{BANNER}\n\n{profile_text}\n"
    # Banner goes under the frontmatter too, so an installed copy declares its origin.
    front_end = body.index("---\n", 4) + 4
    body = body[:front_end] + f"\n{BANNER}\n<!-- profile: {profile_name} -->\n" + body[front_end:]
    out["SKILL.md"] = body
    for ref in sorted((skill_dir / "references").glob("*.md")):
        out[f"references/{ref.name}"] = ref.read_text()
    return out


def build_claude(profile_text, profile_name):
    """path (relative to a .claude dir) -> file contents."""
    files = {}
    for skill_dir in sorted((CORE / "skills").iterdir()):
        if not skill_dir.is_dir():
            continue
        for rel, text in compose_skill(skill_dir, profile_text, profile_name).items():
            files[f"skills/{skill_dir.name}/{rel}"] = text
    for agent in sorted((CORE / "agents").glob("*.md")):
        files[f"agents/{agent.name}"] = agent.read_text()
    for cmd in sorted((CORE / "commands").glob("*.md")):
        if cmd.stem not in COMMANDS:
            sys.exit(f"commands/{cmd.name} is not in COMMANDS in sync.py")
        namespace, name = COMMANDS[cmd.stem]
        files[f"commands/{namespace}/{name}.md"] = cmd.read_text()
    return files


def build_cursor(profile_text, profile_name):
    """One .mdc rule per skill: Cursor has no subagents, so the method travels as rules."""
    files = {}
    for skill_dir in sorted((CORE / "skills").iterdir()):
        if not skill_dir.is_dir():
            continue
        composed = compose_skill(skill_dir, profile_text, profile_name)
        parts = [composed["SKILL.md"]]
        for rel, text in composed.items():
            if rel != "SKILL.md":
                parts.append(f"\n\n---\n\n<!-- {rel} -->\n\n{text}")
        files[f"rules/{skill_dir.name}.mdc"] = "".join(parts)
    return files


def write_tree(base, files, check):
    """Write files under base. Returns the paths that differ (check) or were written."""
    changed = []
    for rel, text in sorted(files.items()):
        path = base / rel
        if check:
            if not path.exists() or path.read_text() != text:
                changed.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            changed.append(path)
    return changed


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--profile", default="areasim", help="a name from profiles/")
    ap.add_argument("--check", action="store_true", help="report staleness, write nothing")
    ap.add_argument("--install", metavar="DIR", help="also install into DIR/.claude")
    args = ap.parse_args()

    profile_text = read_profile(args.profile)
    claude = build_claude(profile_text, args.profile)
    cursor = build_cursor(profile_text, args.profile)

    changed = []
    changed += write_tree(HARNESS / "claude", claude, args.check)
    changed += write_tree(HARNESS / "cursor", cursor, args.check)

    if args.check:
        if changed:
            print("stale:")
            for path in changed:
                print(" ", path.relative_to(ROOT))
            sys.exit(1)
        print("harness is up to date")
        return

    if args.install:
        target = Path(args.install).expanduser().resolve()
        if not target.is_dir():
            sys.exit(f"{target} is not a directory")
        installed = write_tree(target / ".claude", claude, False)
        installed += write_tree(target / ".cursor", cursor, False)
        print(f"installed {len(claude) + len(cursor)} files into {target}")

    print(f"synced {len(claude) + len(cursor)} files (profile: {args.profile}), "
          f"{len(changed)} changed")


if __name__ == "__main__":
    main()
